export function normalizeLanguage(value) {
  const locale = String(value || "en").toLowerCase();
  return Object.prototype.hasOwnProperty.call(SUPPORTED_LANGUAGES, locale) ? locale : "en";
}

export function getLanguageDirection(value) {
  return SUPPORTED_LANGUAGES[normalizeLanguage(value)]?.dir || "ltr";
}

export function getTranslation(locale, key) {
  const normalized = normalizeLanguage(locale);
  const dict = TRANSLATIONS[normalized] || TRANSLATIONS.en;
  return dict[key] ?? TRANSLATIONS.en[key] ?? key;
}
